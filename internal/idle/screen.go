// Package idle generates and manages the idle screen displayed when no media
// is playing. The screen is a simple PNG image with usage instructions.
package idle

import (
	"fmt"
	"image"
	"image/color"
	"image/png"
	"os"
)

const (
	screenWidth  = 1280
	screenHeight = 720
)

var (
	bgColor   = color.RGBA{R: 30, G: 30, B: 35, A: 255}
	textColor = color.RGBA{R: 200, G: 200, B: 200, A: 255}
	dimColor  = color.RGBA{R: 120, G: 120, B: 125, A: 255}
)

// GenerateScreen creates a simple idle screen PNG at the given path.
// The image has a dark background with centered usage instructions rendered
// using a built-in bitmap font (no external font files needed).
func GenerateScreen(outputPath string) error {
	img := image.NewRGBA(image.Rect(0, 0, screenWidth, screenHeight))

	// Fill background.
	for y := 0; y < screenHeight; y++ {
		for x := 0; x < screenWidth; x++ {
			img.Set(x, y, bgColor)
		}
	}

	lines := []struct {
		text string
		col  color.RGBA
	}{
		{"Tap a card to play", textColor},
		{"", textColor},
		{"PLAY / PAUSE    -  play or pause", dimColor},
		{"STOP            -  stop playback", dimColor},
		{"REWIND          -  skip back 10s", dimColor},
		{"FORWARD         -  skip forward 10s", dimColor},
	}

	lineHeight := 28
	totalHeight := len(lines) * lineHeight
	startY := (screenHeight - totalHeight) / 2

	for i, line := range lines {
		if line.text == "" {
			continue
		}
		y := startY + i*lineHeight
		drawString(img, line.text, screenWidth/2, y, line.col)
	}

	f, err := os.Create(outputPath)
	if err != nil {
		return fmt.Errorf("creating idle screen file: %w", err)
	}
	defer f.Close()

	if err := png.Encode(f, img); err != nil {
		return fmt.Errorf("encoding idle screen PNG: %w", err)
	}

	return nil
}

// drawString renders text centered at (cx, y) using a simple 5x7 bitmap font.
func drawString(img *image.RGBA, text string, cx, y int, col color.RGBA) {
	charWidth := 8  // 5px char + 3px spacing
	charHeight := 7 // used for reference, actual drawing uses glyph data

	totalWidth := len(text) * charWidth
	startX := cx - totalWidth/2

	for i, ch := range text {
		x := startX + i*charWidth
		drawChar(img, byte(ch), x, y, col, charHeight)
	}
}

// drawChar renders a single character from the built-in 5x7 bitmap font.
func drawChar(img *image.RGBA, ch byte, x, y int, col color.RGBA, _ int) {
	glyph, ok := font5x7[ch]
	if !ok {
		return
	}
	// Scale 2x for readability on a 720p screen.
	scale := 2
	for row := 0; row < 7; row++ {
		for col_bit := 0; col_bit < 5; col_bit++ {
			if glyph[row]&(1<<(4-col_bit)) != 0 {
				for sy := 0; sy < scale; sy++ {
					for sx := 0; sx < scale; sx++ {
						img.Set(x+col_bit*scale+sx, y+row*scale+sy, col)
					}
				}
			}
		}
	}
}

